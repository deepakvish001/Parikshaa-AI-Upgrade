import { readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { strToU8, zipSync, type Zippable } from "fflate";
import { describe, expect, it } from "vitest";
import { BUNDLE_LIMITS, BundleRefused, canonicalJson, contentHash, contentTypeOf, readBundle, schemaProblems } from "./content-bundle.js";
import { jaccard, ruleProblems, shingles, TextIndex } from "./content-rules.js";
import { CONTENT_SCHEMAS } from "./content/schemas.js";
import { bundleJson, dsaItem, lessonItem, MANIFEST, mcqItem, sqlItem } from "./testing/content-fixtures.js";

/** Reading a content bundle (row 141 part B): the schemas, JSON and ZIP, `$file`, the limits, the hash, and gate 2's rules. */

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const bytes = (text: string) => new TextEncoder().encode(text);
const zip = (files: Record<string, string | Uint8Array>) => zipSync(Object.fromEntries(Object.entries(files).map(([k, v]) => [k, typeof v === "string" ? strToU8(v) : v])) as Zippable);
const manifestDoc = JSON.stringify({ schema: "parikshaa.content/bundle@1", manifest: MANIFEST });

describe("the content schemas", () => {
  it("are the ones in docs/content/schema, generated by scripts/content-schemas.mjs", () => {
    const dir = join(ROOT, "docs", "content", "schema");
    const names = readdirSync(dir).filter((f) => f.endsWith(".schema.json")).sort();
    expect(Object.keys(CONTENT_SCHEMAS).sort()).toEqual(names);
    for (const name of names) expect(CONTENT_SCHEMAS[name], `${name}: run node scripts/content-schemas.mjs`).toEqual(JSON.parse(readFileSync(join(dir, name), "utf8")));
  });

  it("pass the test fixtures, one item of each kind the upload publishes", () => {
    for (const [type, item] of [["dsa-problem", dsaItem()], ["sql-problem", sqlItem()], ["mcq", mcqItem()], ["lesson", lessonItem()]] as const) {
      expect(schemaProblems(type, item), type).toEqual([]);
      expect(ruleProblems(type, item).errors, type).toEqual([]);
    }
  });

  it("say what is wrong with an item in plain words, with where", () => {
    const broken = { ...mcqItem({ correct: 9, extra: 1 }), stem: undefined };
    const problems = schemaProblems("mcq", JSON.parse(JSON.stringify(broken)));
    expect(problems).toEqual(expect.arrayContaining(['(item): missing "stem"', '(item): unknown field "extra"', "correct: must be <= 4"]));
    expect(schemaProblems("dsa-problem", dsaItem({ tags: { topics: [] } }))).toEqual(["tags.topics: must NOT have fewer than 1 items"]);
    expect(schemaProblems("lesson", lessonItem({ sections: [{ kind: "nope", heading: "x", body: "" }] }))).toEqual(
      expect.arrayContaining(['sections[0].kind: must be one of "why", "concept", "example", "misconception", "interview", "summary", "note"', "sections: must NOT have fewer than 5 items"]),
    );
  });
});

describe("a single-file bundle", () => {
  it("gives its manifest and items", () => {
    const bundle = readBundle(bytes(bundleJson([mcqItem(), sqlItem()])));
    expect(bundle.problems).toEqual([]);
    expect(bundle.manifest).toEqual(MANIFEST);
    expect(bundle.items.map((i) => [i.file, contentTypeOf(i.item)])).toEqual([
      ["items[0]", "mcq"],
      ["items[1]", "sql-problem"],
    ]);
  });

  it("says what is wrong with its manifest, and that $file needs a folder", () => {
    const bundle = readBundle(bytes(bundleJson([mcqItem({ solver: { $file: "solver.py" } })], { ...MANIFEST, version: 0, licence: undefined } as never)));
    expect(bundle.problems.map((p) => p.message)).toEqual(expect.arrayContaining(['manifest: manifest: missing "licence"', "manifest: manifest.version: must be >= 1"]));
    expect(bundle.items[0]?.problems).toEqual([{ gate: "file", message: "solver: $file solver.py needs a folder or ZIP bundle; a single JSON file has everything inline" }]);
  });

  it("is refused when it is not a bundle, not JSON, too big, or has too many items", () => {
    const refused = (b: Uint8Array) => {
      try {
        readBundle(b);
      } catch (error) {
        return [(error as BundleRefused).code, (error as Error).message];
      }
      return null;
    };
    expect(refused(bytes(JSON.stringify(mcqItem())))).toEqual(["invalid", expect.stringContaining("not a content bundle")]);
    expect(refused(bytes("{ not json"))).toEqual(["unreadable", expect.stringContaining("neither a ZIP nor JSON")]);
    expect(refused(new Uint8Array([0xff, 0xfe, 0x00]))).toEqual(["unreadable", "The file is not UTF-8 text"]);
    expect(refused(new Uint8Array(BUNDLE_LIMITS.fileBytes + 1))).toEqual(["too_large", expect.stringContaining("at most 20.0 MiB")]);
    expect(refused(bytes(bundleJson(Array.from({ length: BUNDLE_LIMITS.items + 1 }, () => ({ schema: "parikshaa.content/mcq@1" })))))).toEqual(["too_large", expect.stringContaining("at most 600")]);
  });
});

describe("a ZIP bundle", () => {
  it("finds its root by manifest.json, takes every item below it, and fills each $file from beside the item", () => {
    const item = { ...mcqItem(), solver: { $file: "solver.py" }, explanation: { $file: "../shared/explain.md" } };
    const bundle = readBundle(
      zip({
        "batch/manifest.json": manifestDoc,
        "batch/apt/two/item.json": JSON.stringify(item),
        "batch/apt/two/solver.py": "print(1)\n",
        "batch/apt/shared/explain.md": "### Understand\n",
        "batch/notes.json": JSON.stringify({ not: "an item" }),
        "batch/.hidden/item.json": JSON.stringify(mcqItem()),
        "__MACOSX/batch/._item.json": "junk",
      }),
    );
    expect(bundle.problems).toEqual([]);
    expect(bundle.manifest).toEqual(MANIFEST);
    expect(bundle.items).toHaveLength(1);
    expect(bundle.items[0]).toMatchObject({ file: "apt/two/item.json", problems: [] });
    expect(bundle.items[0]?.item).toMatchObject({ solver: "print(1)\n", explanation: "### Understand\n" });
  });

  it("refuses a $file outside the bundle or missing, and a file that is not JSON, item by item", () => {
    const bundle = readBundle(
      zip({
        "manifest.json": manifestDoc,
        "a/item.json": JSON.stringify({ ...mcqItem(), solver: { $file: "../../secret.py" }, explanation: { $file: "missing.md" } }),
        "b.json": "{ nope",
      }),
    );
    expect(bundle.items[0]?.problems).toEqual([
      { gate: "file", message: "explanation: $file missing.md not found" },
      { gate: "file", message: "solver: $file ../../secret.py is outside the bundle" },
    ]);
    expect(bundle.problems).toEqual([{ gate: "file", message: expect.stringMatching(/^b\.json: not JSON/) }]);
  });

  it("refuses the whole ZIP for a path that climbs out, no manifest, too many files, or too much when unpacked", () => {
    const refused = (b: Uint8Array) => {
      try {
        readBundle(b);
        return null;
      } catch (error) {
        return (error as Error).message;
      }
    };
    expect(refused(zip({ "manifest.json": manifestDoc, "../evil.json": "{}" }))).toMatch(/outside its folder/);
    expect(refused(zip({ "item.json": JSON.stringify(mcqItem()) }))).toMatch(/no manifest\.json/);
    expect(refused(zip({ "a/manifest.json": manifestDoc, "b/manifest.json": manifestDoc }))).toMatch(/two manifest\.json/);
    const many: Record<string, string> = { "manifest.json": manifestDoc };
    for (let i = 0; i < BUNDLE_LIMITS.entries; i++) many[`f${i}.txt`] = "x";
    expect(refused(zip(many))).toMatch(/more than 2000 files/);
    // A bomb: 61 MiB of zeros compresses to almost nothing.
    const bomb = zipSync({ "manifest.json": strToU8(manifestDoc), "zeros.txt": [new Uint8Array(BUNDLE_LIMITS.inflatedBytes + 1024 * 1024), { level: 9 }] });
    expect(bomb.length).toBeLessThan(BUNDLE_LIMITS.fileBytes);
    expect(refused(bomb)).toMatch(/more than 60\.0 MiB when unpacked/);
  });
});

describe("the content hash", () => {
  it("is the same whatever order an item's keys come in, and changes with its content", () => {
    expect(canonicalJson({ b: [1, { d: 2, c: 3 }], a: "x" })).toBe('{"a":"x","b":[1,{"c":3,"d":2}]}');
    expect(contentHash({ b: 1, a: 2 })).toBe(contentHash({ a: 2, b: 1 }));
    expect(contentHash({ a: 2 })).not.toBe(contentHash({ a: 3 }));
    expect(contentHash(mcqItem())).toMatch(/^[0-9a-f]{64}$/);
  });
});

describe("gate 2: what an item means", () => {
  it("finds what the schema cannot: missing references, keys out of range, sections out of order", () => {
    const dsa = dsaItem({ solutions: dsaItem().solutions.filter((s) => s.lang !== "java"), level: "L3" });
    expect(ruleProblems("dsa-problem", dsa).errors).toEqual(expect.arrayContaining(["solutions: no java reference", "level L3 goes with difficulty hard, not easy"]));
    expect(ruleProblems("mcq", mcqItem({ correct: 4 })).errors).toEqual(["correct is past the last option"]);
    // Pictures cannot come in a bundle yet (MCQ_IMAGES_PASS, waiting on the owner): such a question fails, and says why.
    expect(ruleProblems("mcq", mcqItem({ images: [{ file: "chart.png", alt: "Sales of the stall by month." }] })).errors).toEqual([expect.stringMatching(/^images: pictures in an upload are not taken yet/)]);
    const lesson = lessonItem();
    expect(ruleProblems("lesson", { ...lesson, sections: [...lesson.sections].reverse() }).errors).toEqual(["sections: the first section is the why"]);
    expect(ruleProblems("sql-problem", sqlItem({ editorial: "## Problem\n\nSee https://leetcode.com/problems/x" })).errors).toEqual(expect.arrayContaining(["links to another problem site (leetcode.com): use our own slugs in related"]));
  });

  it("finds a copied text, and one close enough for a reviewer to look at", () => {
    const text = (n: number) => shingles(lessonItem().sections.map((s) => s.body).join(" ").split(" ").slice(0, n).join(" "));
    expect(jaccard(text(400), text(400))).toBe(1);
    const index = new TextIndex();
    index.add({ label: "the site's lesson a", key: "lesson:a", shingles: text(400) });
    expect(index.closest({ label: "b", key: "lesson:b", shingles: text(400) })).toEqual({ label: "the site's lesson a", similarity: 1 });
    const close = index.closest({ label: "b", key: "lesson:b", shingles: text(300) })?.similarity ?? 0;
    expect(close).toBeGreaterThanOrEqual(0.6);
    expect(close).toBeLessThan(1);
    // Its own earlier version is not a duplicate of it.
    expect(index.closest({ label: "a", key: "lesson:a", shingles: text(400) })).toBeNull();
    expect(index.closest({ label: "c", key: "problem:c", shingles: shingles(dsaItem().statement) })).toBeNull();
  });
});
