export function prepText(language: string, key: PrepKey, vars: Readonly<Record<string, string | number>> = {}): string {
  const table: Record<PrepKey, string> = language === "hi" ? hi : en;
  return table[key].replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function usePrepText(): (key: PrepKey, vars?: Readonly<Record<string, string | number>>) => string {
  const { language } = usePreferences();
  return useCallback((key, vars) => prepText(language, key, vars), [language]);
}

export const PREP_TABLES = { en, hi };
