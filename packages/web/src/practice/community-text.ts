export function communityText(language: string, key: CommunityKey, vars: Readonly<Record<string, string | number>> = {}): string {
  const table: Record<CommunityKey, string> = language === "hi" ? hi : en;
  return table[key].replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

export function useCommunityText(): (key: CommunityKey, vars?: Readonly<Record<string, string | number>>) => string {
  const { language } = usePreferences();
  return useCallback((key, vars) => communityText(language, key, vars), [language]);
}

export const COMMUNITY_TABLES = { en, hi };
