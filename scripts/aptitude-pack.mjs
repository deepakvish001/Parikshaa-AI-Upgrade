#!/usr/bin/env node
// Builds packages/api/src/content/aptitude-starter.ts (K2-8) from the content kit's aptitude samples
// (content/samples/aptitude): each item exactly as the bulk upload publishes it, through content-publish.ts's
// `project`, its default variant set filled with the values its solver derives for that set (python3, as
// scripts/content-validate.mjs runs MCQ solvers). Order: quant, logical, verbal, then each item's placement.
//
//   npm run build && node scripts/aptitude-pack.mjs
//
// The module is committed, so the server never reads content/; aptitude-starter.test.ts holds each question to its
// sample. Run this again after a sample changes.

import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const { project } = await import(pathToFileURL(join(root, "packages/api/dist/content-publish.js")).href);
const dir = join(root, "content/samples/aptitude");
const SECTIONS = ["aptitude-quant", "aptitude-logical", "aptitude-verbal"];
const items = readdirSync(dir)
  .map((name) => JSON.parse(readFileSync(join(dir, name, "item.json"), "utf8")))
  .sort(
    (a, b) =>
      SECTIONS.indexOf(a.section) - SECTIONS.indexOf(b.section) || (a.placement?.[0]?.position ?? 0) - (b.placement?.[0]?.position ?? 0) || a.slug.localeCompare(b.slug),
  );

const questions = items.map((item) => {
  let values = {};
  if (item.solver !== undefined) {
    const ran = spawnSync("python3", ["-I", "-c", item.solver], { input: JSON.stringify(item.variants?.sets[0] ?? {}), encoding: "utf8" });
    if (ran.status !== 0) throw new Error(`${item.slug}: ${ran.stderr}`);
    values = JSON.parse(ran.stdout).values ?? {};
  }
  const projected = project("mcq", item, { values });
  if (projected.kind !== "problem") throw new Error(`${item.slug}: not a problem`);
  const p = projected.problem;
  const { id: _id, maxScore: _max, rubric: _rubric, ...question } = p.question;
  if (/\{\{[a-z]/.test(JSON.stringify(question)) || /\{\{[a-z]/.test(p.editorial)) throw new Error(`${item.slug}: a {{name}} is left unfilled`);
  return { slug: p.slug, title: p.title, difficulty: p.difficulty, tags: p.tags, question, editorial: p.editorial };
});

const pack = { source: "content/samples/aptitude (row 141 part A), default variant set", questions };
writeFileSync(
  join(root, "packages/api/src/content/aptitude-starter.ts"),
  [
    "// Generated by scripts/aptitude-pack.mjs from content/samples/aptitude. Do not edit by hand.",
    'import type { AptitudePack } from "./packs.js";',
    "",
    "/** Offered to no site until the owner approves its content (F6): PENDING_PACKS in starter-packs.ts. */",
    `export const APTITUDE_STARTER: AptitudePack = ${JSON.stringify(pack, null, 2)};`,
    "",
  ].join("\n"),
);
console.log(questions.map((q) => `${q.slug}  ${q.question.kind}  ${q.tags.join(", ")}`).join("\n"));
