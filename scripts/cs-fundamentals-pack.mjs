#!/usr/bin/env node
// Builds packages/api/src/content/cs-fundamentals.ts from Parikshaa-New's
// CS question bank (src/data/csSubjectsData.ts): each topic's questions and
// answers become a lesson, and each question with options a practice MCQ whose
// editorial is the answer.
//
//   node scripts/cs-fundamentals-pack.mjs <path to a Parikshaa-New checkout>
//
// The module is committed, so the server never needs Parikshaa-New; run this
// again only to take in new questions from it.

import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

const root = process.argv[2];
if (root === undefined) {
  console.error("usage: node scripts/cs-fundamentals-pack.mjs <parikshaa-new checkout>");
  process.exit(2);
}
const source = resolve(root, "src/data/csSubjectsData.ts");
const dir = await mkdtemp(join(tmpdir(), "cs-pack-"));
try {
  const out = join(dir, "cs.mjs");
  await build({ entryPoints: [source], bundle: true, format: "esm", platform: "node", outfile: out, logLevel: "error" });
  const { csSubjects, csTopics, csQuestions } = await import(pathToFileURL(out).href);
  let commit = "unknown";
  try {
    commit = execFileSync("git", ["-C", root, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
  } catch {
    // Not a git checkout: say so in the pack.
  }
  const difficulty = (d) => (d === "Hard" ? "hard" : d === "Medium" ? "medium" : "easy");
  const clean = (text) => text.replace(/^ /gm, "").trim();
  const subjects = csSubjects
    .map((s) => ({
      id: s.id,
      name: s.name,
      topics: csTopics
        .filter((t) => t.subjectId === s.id)
        .map((t) => ({
          id: t.id,
          name: t.name,
          questions: csQuestions
            .filter((q) => q.topicId === t.id)
            .map((q) => ({
              title: q.title.trim(),
              text: q.text.trim(),
              difficulty: difficulty(q.difficulty),
              answer: clean(q.answer),
              options: (q.options ?? []).map((o) => o.text.trim()),
              correct: (q.options ?? []).findIndex((o) => o.isCorrect),
            })),
        }))
        .filter((t) => t.questions.length > 0),
    }))
    .filter((s) => s.topics.length > 0);
  const pack = { source: `deepakvish001/Parikshaa-New@${commit}:src/data/csSubjectsData.ts`, subjects };
  const target = resolve(import.meta.dirname, "../packages/api/src/content/cs-fundamentals.ts");
  await writeFile(
    target,
    `// Generated by scripts/cs-fundamentals-pack.mjs from ${pack.source}. Do not edit by hand.\n` +
      `import type { CsPack } from "./packs.js";\n\n` +
      `export const CS_FUNDAMENTALS: CsPack = ${JSON.stringify(pack, null, 2)};\n`,
  );
  const count = subjects.reduce((n, s) => n + s.topics.reduce((m, t) => m + t.questions.length, 0), 0);
  console.log(`wrote ${target}: ${subjects.length} subjects, ${count} questions`);
} finally {
  await rm(dir, { recursive: true, force: true });
}
