#!/usr/bin/env node
/**
 * Copies the content format's JSON Schemas (docs/content/schema/*.schema.json) into the API as a module,
 * packages/api/src/content/schemas.ts, which the console's bulk upload checks every item against (row 141, part B).
 * The API's container has no docs/ folder, so the schemas travel with the code.
 *
 *   node scripts/content-schemas.mjs          write the module
 *   node scripts/content-schemas.mjs --check  exit 1 if the module differs from the schemas (packages/api's test does the same)
 *
 * Run it whenever a schema in docs/content/schema changes.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMA_DIR = join(ROOT, "docs", "content", "schema");
const OUT = join(ROOT, "packages", "api", "src", "content", "schemas.ts");

export function render() {
  const schemas = {};
  for (const name of readdirSync(SCHEMA_DIR).filter((f) => f.endsWith(".schema.json")).sort()) {
    schemas[name] = JSON.parse(readFileSync(join(SCHEMA_DIR, name), "utf8"));
  }
  return [
    "// Generated by scripts/content-schemas.mjs from docs/content/schema/*.schema.json. Do not edit by hand:",
    "// change the schema in docs/content/schema, then run `node scripts/content-schemas.mjs`.",
    "",
    "/** The content format's JSON Schemas (draft 2020-12), by file name. */",
    `export const CONTENT_SCHEMAS: Readonly<Record<string, Readonly<Record<string, unknown>>>> = ${JSON.stringify(schemas, null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUT, "utf8");
    if (current !== text) {
      process.stderr.write("packages/api/src/content/schemas.ts is out of date: run node scripts/content-schemas.mjs\n");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, text);
    process.stdout.write(`wrote ${OUT}\n`);
  }
}
